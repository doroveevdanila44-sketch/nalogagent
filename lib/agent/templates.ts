/** Приветствие по времени суток клиента: 5-11 утро, 12-17 день, 18-22 вечер, ночью нейтральное. */
export function greetingFor(hour: number): string {
  if (hour >= 5 && hour < 12) return GREETINGS.morning;
  if (hour >= 12 && hour < 18) return GREETINGS.day;
  if (hour >= 18 && hour < 23) return GREETINGS.evening;
  return GREETINGS.generic;
}

