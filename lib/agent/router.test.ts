describe('классификация на 100 фразах', () => {
  const opts = { entities };
  const wrong: string[] = [];
  for (const t of ON_TOPIC) if (classify(t, opts).cls !== 'A') wrong.push(`A≠ ${t}`);
  for (const t of ETIQUETTE) {
    const c = classify(t, opts).cls;
    if (c !== 'B' && c !== 'C') wrong.push(`B≠ ${t} → ${c}`);
  }
  for (const t of OFF_TOPIC) if (classify(t, opts).cls !== 'D') wrong.push(`D≠ ${t}`);

  it('не больше 5 ошибок', () => {
    expect(ON_TOPIC.length + ETIQUETTE.length + OFF_TOPIC.length).toBe(100);
    expect(wrong, wrong.join('\n')).toHaveLength(Math.min(wrong.length, 5));
  });
  it('в этом корпусе ошибок нет вовсе', () => {
    expect(wrong).toEqual([]);
  });
});

describe('маршрутизация особых случаев', () => {
  it('схемы обхода это класс F, даже с НДС в фразе', () => {
    expect(classify('Как раздробить бизнес, чтобы не заметили').cls).toBe('F');
    expect(classify('как обойти НДС через несколько ИП', { entities }).cls).toBe('F');
    expect(classify('как спрятать выручку от налоговой').cls).toBe('F');
  });
  it('признаки дробления это тема', () => {
    expect(classify('Какие признаки дробления видны?').cls).toBe('A');
  });
  it('непонятное это класс E', () => {
    expect(classify('а по той компании?', { entities: [] }).cls).toBe('E');
    expect(classify('ну это самое').cls).toBe('E');
  });
  it('юрлицо без слов темы это тема', () => {
    expect(classify('а по Бете?', { entities }).cls).toBe('A');
  });
  it('число при незавершённом запросе это ответ на уточнение', () => {
    const pending = { intent: 'scenario' as const, missing: ['cars' as const, 'price' as const] };
    expect(classify('3 по 7', { entities, pending }).cls).toBe('A');
  });
  it('приветствие с темой уходит в тему', () => {
    expect(classify('Привет, какая ставка выгоднее?', { entities }).cls).toBe('A');
  });
  it('шутка про налоги это отказ, а не расчёт', () => {
    // слово «налог» слабое, «анекдот» явно не по теме
    expect(classify('Расскажи анекдот про налоги').cls).toBe('D');
  });
});
