import { describe, expect, it } from 'vitest';
import { aliasesFor } from './pipeline';
import { classify, mentionsEntity } from './router';
import type { EntityRef } from './types';

const entities: EntityRef[] = [
  { id: 'alfa', name: 'ООО «Альфа»' },
  { id: 'beta', name: 'ИП Бета' },
  { id: 'delta', name: 'ИП Дельта' },
  { id: 'gamma', name: 'ООО «Гамма»' },
].map((e) => ({ ...e, aliases: aliasesFor(e.name) }));

describe('юрлица в падежах', () => {
  for (const [text, id] of [
    ['по Альфе', 'alfa'],
    ['у Беты какая ставка', 'beta'],
    ['для Дельты', 'delta'],
    ['Гамма', 'gamma'],
    ['ООО Альфа', 'alfa'],
    ['с Гаммой что', 'gamma'],
  ] as const) {
    it(`«${text}» это ${id}`, () => {
      expect(mentionsEntity(text, entities)?.id).toBe(id);
    });
  }
  it('посторонние слова не совпадают', () => {
    expect(mentionsEntity('бетон и альфабет', entities)).toBeNull();
  });
});

